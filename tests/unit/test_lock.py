"""tools.lock: the file format, reading and writing."""

from __future__ import annotations

from pathlib import Path

import pytest

from cyberfw.exceptions import LockError
from cyberfw.manager.lock import LockedAsset, LockedTool, ToolLock, dump_lock, read_lock, write_lock

_HEX_A = "a" * 64


def _asset(name: str, sha256: str = _HEX_A, source: str = "digest") -> LockedAsset:
    return LockedAsset(name=name, url=f"https://example.test/{name}", sha256=sha256, source=source)  # type: ignore[arg-type]


def _lock() -> ToolLock:
    return ToolLock(
        tools={
            "subfinder": LockedTool(
                repo="projectdiscovery/subfinder",
                tag="v2.17.0",
                assets={
                    "windows/amd64": _asset("subfinder_2.17.0_windows_amd64.zip"),
                    "linux/amd64": _asset("subfinder_2.17.0_linux_amd64.zip", "0" * 64, "checksums"),
                },
            ),
            "gowitness": LockedTool(
                repo="sensepost/gowitness",
                tag="3.2.2",
                assets={"linux/amd64": _asset("gowitness-3.2.2-linux-amd64", "b" * 64, "download")},
            ),
        }
    )


_VALID = (
    "version: 1\n"
    "tools:\n"
    "  t:\n"
    "    repo: o/t\n"
    "    tag: v1.0.0\n"
    "    assets:\n"
    "      linux/amd64:\n"
    "        name: t.zip\n"
    "        url: https://example.test/t.zip\n"
    f"        sha256: {_HEX_A}\n"
    "        source: digest\n"
)


class TestLockFile:
    def test_round_trip(self, tmp_path: Path) -> None:
        path = tmp_path / "tools.lock"
        write_lock(path, _lock())

        assert read_lock(path) == _lock()

    def test_missing_file_is_no_lock(self, tmp_path: Path) -> None:
        assert read_lock(tmp_path / "tools.lock") is None

    def test_rewriting_an_unchanged_lock_is_byte_identical(self, tmp_path: Path) -> None:
        path = tmp_path / "tools.lock"
        write_lock(path, _lock())
        first = path.read_bytes()

        reread = read_lock(path)
        assert reread is not None
        write_lock(path, reread)

        assert path.read_bytes() == first

    def test_tools_are_sorted_and_platforms_follow_the_supported_order(self) -> None:
        text = dump_lock(_lock())

        assert text.index("gowitness:") < text.index("subfinder:")
        assert text.index("linux/amd64:") < text.index("windows/amd64:")

    def test_the_file_starts_with_the_do_not_edit_header(self) -> None:
        assert dump_lock(_lock()).startswith("# tools.lock — generated by `cyberfw lock`; do not edit by hand.")

    def test_it_is_written_with_lf_line_endings(self, tmp_path: Path) -> None:
        path = tmp_path / "tools.lock"
        write_lock(path, _lock())

        assert b"\r\n" not in path.read_bytes()

    def test_a_number_like_tag_stays_a_string(self, tmp_path: Path) -> None:
        path = tmp_path / "tools.lock"
        tool = LockedTool(repo="o/t", tag="2.4", assets={"linux/amd64": _asset("t.zip")})
        write_lock(path, ToolLock(tools={"t": tool}))

        lock = read_lock(path)

        assert lock is not None and lock.tools["t"].tag == "2.4"

    def test_version_drops_a_leading_v(self) -> None:
        assert LockedTool(repo="o/t", tag="v1.2.3", assets={}).version == "1.2.3"
        assert LockedTool(repo="o/t", tag="3.2.2", assets={}).version == "3.2.2"

    @pytest.mark.parametrize(
        "text",
        [
            _VALID.replace(_HEX_A, "xyz"),
            _VALID.replace("https://", "http://"),
            _VALID.replace("source: digest", "source: guess"),
            _VALID.replace("version: 1", "version: 2"),
            _VALID.replace("version: 1\n", ""),
            _VALID + "    extra: 1\n",
            "- just\n- a list\n",
            "version: [1\n",
            "<<<<<<< HEAD\n" + _VALID + "=======\n" + _VALID + ">>>>>>> theirs\n",
        ],
        ids=["bad-hash", "http-url", "unknown-source", "unknown-format", "no-version", "unknown-key",
             "not-a-mapping", "broken-yaml", "merge-conflict"],
    )
    def test_a_malformed_lock_is_a_lock_error_naming_the_file(self, tmp_path: Path, text: str) -> None:
        path = tmp_path / "tools.lock"
        path.write_text(text, encoding="utf-8")

        with pytest.raises(LockError, match="tools.lock"):
            read_lock(path)

    def test_an_unwritable_location_is_a_lock_error_and_keeps_the_old_file(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        path = tmp_path / "tools.lock"
        path.write_text(_VALID, encoding="utf-8")

        def refuse(src: object, dst: object) -> None:
            raise PermissionError(13, "Permission denied")

        monkeypatch.setattr("cyberfw.manager.lock.os.replace", refuse)

        with pytest.raises(LockError, match="workspace"):
            write_lock(path, _lock())

        assert path.read_text(encoding="utf-8") == _VALID
        assert not (tmp_path / "tools.lock.tmp").exists()
