LOG = get_logger("manager.lock")

#: The lock's file name; it lives next to the ``registry.yaml`` it pins.
LOCK_NAME = "tools.lock"
#: The file-format version this cyberfw writes and reads.
LOCK_FORMAT = 1
#: Version of the asset-selection rules (``installer.select_asset``). Bump it
#: whenever a change to the rules can pick a different file for an existing
#: tool: entries locked under the old rules then read as stale, so
#: ``cyberfw lock`` re-resolves them instead of ``--upgrade`` mistaking the new
#: pick for an upstream change.
SELECTION_RULES = 1

#: Where a locked hash came from: the GitHub API's asset digest, the release's
#: own checksums file, or hashing the downloaded asset at lock time.
HashSource = Literal["digest", "checksums", "download"]

_HEADER = (
    "# tools.lock — generated by `cyberfw lock`; do not edit by hand.\n"
    "# Pins every downloaded tool to one release and the SHA-256 of each platform's\n"
    "# asset. `cyberfw init` installs exactly these and refuses an archive whose hash\n"
    "# differs. Change pins with `cyberfw lock [--upgrade] [tool ...]` and commit.\n"
)

_SHA256 = re.compile(r"[0-9a-f]{64}")


class LockedAsset(BaseModel):
    """One platform's asset of a locked release."""

    model_config = ConfigDict(extra="forbid")

    name: str
    url: str
    sha256: str
    source: HashSource

    @field_validator("url")
    @classmethod
    def _https(cls, value: str) -> str:
        if not value.startswith("https://"):
            raise ValueError(f"must be an https:// URL, got {value!r}")
        return value

    @field_validator("sha256")
    @classmethod
    def _hex(cls, value: str) -> str:
        if not _SHA256.fullmatch(value):
            raise ValueError("must be 64 lowercase hex characters")
        return value


class LockedTool(BaseModel):
    """One tool pinned to a release: its repo, tag and asset per platform."""

    model_config = ConfigDict(extra="forbid")

    repo: str
    tag: str
    #: :func:`selection_fingerprint` of the registry entry the assets were picked
    #: with; empty for an entry locked before fingerprints (always stale).
    selection: str = ""
    #: ``Mapping.label`` (``"linux/amd64"``) → that platform's asset.
    assets: dict[str, LockedAsset]

    @property
    def version(self) -> str:
        """``1.2.3`` for tag ``v1.2.3`` — the form the install state records."""
        return self.tag.lstrip("vV")

    @property
    def sources(self) -> str:
        """Where its hashes came from, e.g. ``"checksums, digest"``."""
        return ", ".join(sorted({asset.source for asset in self.assets.values()}))


class ToolLock(BaseModel):
    """The whole ``tools.lock`` document."""

    model_config = ConfigDict(extra="forbid")

    version: int = LOCK_FORMAT
    tools: dict[str, LockedTool] = Field(default_factory=dict)

    @field_validator("version")
    @classmethod
    def _known_format(cls, value: int) -> int:
        if value != LOCK_FORMAT:
            raise ValueError(f"unsupported lock format {value} (this cyberfw reads {LOCK_FORMAT})")
        return value


def read_lock(path: Path) -> ToolLock | None:
    """Parse ``path``; ``None`` when there is no such file.

    Anything malformed — YAML, schema, a hash or URL, an unknown format
    version, leftover merge-conflict markers — is a :class:`LockError` naming
    the file.
    """
    if not path.is_file():
        return None
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
    except UnicodeDecodeError as exc:
        # Windows PowerShell 5.1 saves UTF-16 with `>` and cp1252 with Set-Content.
        raise LockError(
            f"cannot read {path}: it is not UTF-8 ({exc.reason} at byte {exc.start}) — "
            "save it as UTF-8 or regenerate it with `cyberfw lock`"
        ) from exc
    except (OSError, yaml.YAMLError) as exc:
        raise LockError(f"cannot read {path}: {exc}") from exc
    if not isinstance(document, dict) or "version" not in document:
        raise LockError(f"{path}: not a cyberfw lock file (expected `version:` and `tools:`)")
    try:
        return ToolLock.model_validate(document)
    except ValidationError as exc:
        problems = "; ".join(
            f"{'.'.join(str(part) for part in err['loc']) or '<root>'}: {err['msg']}" for err in exc.errors()
        )
        raise LockError(f"{path}: {problems}") from exc


def _platform_rank(label: str) -> tuple[int, str]:
    labels = [mapping.label for mapping in SUPPORTED_PLATFORMS]
    return (labels.index(label) if label in labels else len(labels), label)


def dump_lock(lock: ToolLock) -> str:
    """The file's text: the header, then tools by name with their platforms in
    :data:`SUPPORTED_PLATFORMS` order — deterministic, so an unchanged lock
    rewrites byte-identical and a git diff shows only real changes."""
    document = {
        "version": lock.version,
        "tools": {
            name: {
                "repo": tool.repo,
                "tag": tool.tag,
                "selection": tool.selection,
                "assets": {
                    label: {"name": asset.name, "url": asset.url, "sha256": asset.sha256, "source": asset.source}
                    for label, asset in sorted(tool.assets.items(), key=lambda item: _platform_rank(item[0]))
                },
            }
            for name, tool in sorted(lock.tools.items())
        },
    }
    return _HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=1000)


def write_lock(path: Path, lock: ToolLock) -> None:
    """Write ``lock`` to ``path`` atomically — a temp file, then ``os.replace`` —
    so an interrupted write never leaves a half-written lock behind."""
    tmp = path.with_name(path.name + ".tmp")
    try:
        tmp.write_text(dump_lock(lock), encoding="utf-8", newline="\n")
        os.replace(tmp, path)
    except OSError as exc:
        with contextlib.suppress(OSError):
            tmp.unlink(missing_ok=True)
        raise LockError(
            f"cannot write {path}: {exc} — run cyberfw from a workspace "
            "(a directory with registry.yaml) to change pins"
        ) from exc


class ReleaseSource(Protocol):
    """What resolving a lock entry needs from :class:`GitHubClient`."""

    def release(self, owner: str, repo: str, tag: str) -> GitHubRelease: ...

    def fetch_text(self, url: str) -> str: ...

    def download(self, url: str, destination: Path, *, expected_size: int | None = None) -> None: ...


def resolve_tool(client: ReleaseSource, spec: ToolSpec, *, work_dir: Path) -> LockedTool:
    """Pin ``spec`` to one release and record the SHA-256 of its asset on every
    supported platform.

    The release is the registry's ``version:`` tag when pinned, else the latest.
    :func:`select_asset` picks each platform's asset exactly as the installer
    would; a platform the release has no asset for is left out. A hash comes
    from the asset's API digest and/or the release's ``checksums.txt`` — both
    present and different is a :class:`LockError` — or, with neither, from
    downloading the asset into ``work_dir`` (removed again once hashed).
    """
    release = client.release(spec.repo_owner, spec.repo_name, spec.version)
    checksums = client.fetch_text(release.checksums_url) if release.checksums_url else ""
    hashed: dict[str, tuple[str, HashSource]] = {}
    assets: dict[str, LockedAsset] = {}
    for mapping in SUPPORTED_PLATFORMS:
        asset = select_asset(release, spec, mapping)
        if asset is None:
            continue
        if asset.name not in hashed:
            hashed[asset.name] = _hash_of(client, asset, checksums, work_dir)
        sha256, source = hashed[asset.name]
        try:
            assets[mapping.label] = LockedAsset(name=asset.name, url=asset.url, sha256=sha256, source=source)
        except ValidationError as exc:
            raise LockError(f"{spec.name}: cannot lock {asset.name}: {exc.errors()[0]['msg']}") from exc
    if not assets:
        raise LockError(
            f"{spec.name}: release {release.tag} of {spec.repo} has no asset for any supported platform"
        )
    return LockedTool(repo=spec.repo, tag=release.tag, selection=selection_fingerprint(spec), assets=assets)


def selection_fingerprint(spec: ToolSpec) -> str:
    """What decides which file each platform gets: the selection rules, the
    supported platforms and the tool's ``asset_patterns``. Stored with each lock
    entry; when it no longer matches, the entry is stale and ``cyberfw lock``
    re-resolves it."""
    payload = json.dumps(
        {
            "rules": SELECTION_RULES,
            "platforms": [mapping.label for mapping in SUPPORTED_PLATFORMS],
            "asset_patterns": spec.asset_patterns,
        },
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:16]


def _hash_of(
    client: ReleaseSource, asset: ReleaseAsset, checksums: str, work_dir: Path
) -> tuple[str, HashSource]:
    listed = checksum_for(checksums, asset.name) if checksums else None
    if asset.digest is not None and listed is not None and asset.digest != listed:
        raise LockError(
            f"digest and checksums.txt disagree for {asset.name} "
            f"(GitHub {asset.digest}, checksums.txt {listed}) — refusing to lock it"
        )
    if asset.digest is not None:
        return asset.digest, "digest"
    if listed is not None:
        return listed, "checksums"
    LOG.info("%s: no published digest or checksum — downloading it to hash it", asset.name)
    target = work_dir / asset.name
    try:
        client.download(asset.url, target, expected_size=asset.size or None)
        return sha256_hex(target), "download"
    finally:
        # Windows Defender may still be scanning the file it just saw arrive; it
        # lives in a throwaway directory, so failing to delete it must not lose
        # the hash (or the whole lock run).
        with contextlib.suppress(OSError):
            target.unlink(missing_ok=True)


def stale_reason(spec: ToolSpec, entry: LockedTool) -> str | None:
    """Why ``entry`` no longer satisfies ``spec``'s registry entry, or ``None``."""
    if entry.repo.lower() != spec.repo.lower():
        return f"repo changed (lock: {entry.repo}, registry: {spec.repo})"
    if spec.pinned_version is not None and entry.version != spec.pinned_version:
        return f"registry pins {spec.version}, lock has {entry.tag}"
    if entry.selection != selection_fingerprint(spec):
        return "asset selection changed (the registry's asset_patterns or cyberfw's selection rules)"
    return None


#: How ``cyberfw lock`` changed one tool's entry.
ChangeKind = Literal["added", "upgraded", "re-resolved", "updated", "removed", "unchanged", "failed"]


@dataclass(frozen=True)
class LockChange:
    """One row of ``cyberfw lock``'s report."""

    tool: str
    before: str | None  # the locked tag before; None when it was not locked
    after: str | None  # the locked tag now; None when removed or not resolved
    change: ChangeKind
    sources: str = ""
    error: str = ""


@dataclass(frozen=True)
class LockUpdate:
    """What updating the lock did."""

    changes: list[LockChange]
    written: bool
    path: Path

    @property
    def failed(self) -> bool:
        return any(change.change == "failed" for change in self.changes)


def replaced_files(locked: LockedTool, fresh: LockedTool) -> list[str]:
    """Platforms whose locked file is still picked but now has another SHA-256 —
    under one tag, upstream replaced a file it had already published."""
    return [
        label
        for label, asset in locked.assets.items()
        if label in fresh.assets and fresh.assets[label].name == asset.name and fresh.assets[label].sha256 != asset.sha256
    ]


def reselected_platforms(locked: LockedTool, fresh: LockedTool) -> list[str]:
    """Platforms that now get a different file. Under one tag and unchanged
    selection rules, that means the release's asset list changed upstream."""
    return [
        label for label, asset in locked.assets.items() if label in fresh.assets and fresh.assets[label].name != asset.name
    ]
