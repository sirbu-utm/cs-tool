"""tools.lock — every downloaded tool pinned to one release and verified by hash.

``registry.yaml`` is the intent: which tools, from where, optionally which
``version:``. ``tools.lock`` is the resolved state: the exact release tag of each
tool and the SHA-256 of its asset on every supported platform. ``cyberfw init``
installs exactly what it pins and refuses an archive whose hash differs;
``cyberfw lock`` is the only writer. The file is committed next to the registry
it pins, so every machine installs byte-identical tools.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Literal, Protocol

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from cyberfw.exceptions import LockError
from cyberfw.logging import get_logger
